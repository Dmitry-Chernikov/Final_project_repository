package org.aston.app.random;

import org.aston.app.model.Car;

/**
 * Интерфейс RandomGeneration определяет контракт для генерации объектов Car со случайными данными.
 * <p>
 * Классы, реализующие этот интерфейс, отвечают за создание экземпляров автомобиля
 * с различными характеристиками (модель, мощность, год выпуска) в соответствии с определённой стратегией.
 * <p>
 * Позволяет реализовать принцип инъекции зависимости, обеспечивая гибкость
 * при выборе типа генерации (например, низкая, средняя, высокая мощность, спорткары и т.д.).
 */
public interface RandomGeneration {

    /**
     * Создаёт и возвращает новый объект Car со случайно сгенерированными полями.
     * <p>
     * Конкретная реализация определяет, как именно генерируются значения:
     * какие модели доступны, в каком диапазоне мощность, и т.п.
     *
     * @return объект Car, построенный с использованием паттерна Builder
     */
    Car randomCar();
}
