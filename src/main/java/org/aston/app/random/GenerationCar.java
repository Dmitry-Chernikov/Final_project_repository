package org.aston.app.random;

import org.aston.app.model.Car;

/**
 * Класс GenerationCar предназначен для генерации объектов автомобилей с использованием стратегии случайной генерации.
 * <p>
 * Инкапсулирует логику создания случайного автомобиля, делегируя непосредственную генерацию
 * внешнему объекту типа RandomGeneration. Поддерживает принцип инверсии зависимости (DI),
 * позволяя легко заменять способ генерации в тестах или при расширении функциональности.
 */
public class GenerationCar {
    /**
     * Объект, отвечающий за генерацию данных для создания автомобиля.
     * Предоставляет методы для получения случайных значений модели, мощности и года выпуска.
     */
    private RandomGeneration random;

    /**
     * Конструктор класса GenerationCar.
     *
     * @param random объект реализации RandomGeneration, который будет использоваться для генерации данных
     * @throws NullPointerException если переданный объект random равен null
     */
    public GenerationCar(RandomGeneration random) {
        this.random = random;
    }

    /**
     * Создаёт и возвращает новый объект Car со случайно сгенерированными полями.
     * <p>
     * Использует делегирование к объекту random для получения значений всех полей автомобиля.
     *
     * @return новый экземпляр Car с заполненными моделью, мощностью и годом выпуска
     */
    public Car generationRandomCar() {
        return random.randomCar();
    }
}
