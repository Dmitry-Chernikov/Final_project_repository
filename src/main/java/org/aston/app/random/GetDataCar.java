package org.aston.app.random;

/**
 * Абстрактный класс GetDataCar служит контейнером для хранения массивов модификаций автомобилей
 * различных производителей. Каждый массив содержит строковые названия моделей, которые могут
 * быть использованы при генерации полного названия автомобиля.
 * <p>
 * Класс объявлен как абстрактный, так как предназначен для наследования и заполнения данных
 * в подклассах. Не содержит реализации методов — только поля.
 */
public abstract class GetDataCar {
    /**
     * Массив строк с модификациями автомобилей производителя Audi (например, "A4", "Q7").
     */
    String[] AUDI;

    /**
     * Массив строк с модификациями автомобилей производителя Toyota (например, "Camry", "Prius").
     */
    String[] TOYOTA;

    /**
     * Массив строк с модификациями автомобилей производителя Ford (например, "Fiesta", "Focus").
     */
    String[] FORD;

    /**
     * Массив строк с модификациями автомобилей производителя BMW (например, "X5", "M3").
     */
    String[] BMW;
}
