package org.aston.app.test;

/**
 * Класс CustomTestRunner предназначен для запуска ручных тестов компонентов приложения.
 * <p>
 * Содержит статический метод run(), который последовательно вызывает тесты
 * для различных модулей: построения объектов Car, стратегий сортировки и генератора данных.
 * <p>
 * Используется вместо сторонних тестовых фреймворков (например, JUnit),
 * в соответствии с требованиями задания — тесты реализованы вручную.
 */
public class CustomTestRunner {

    /**
     * Запускает все тесты приложения.
     * <p>
     * Выводит информационные сообщения о начале и завершении тестирования.
     * Вызывает методы запуска тестов для каждого компонента системы:
     * - Проверка работы паттерна Builder для класса Car
     * - Проверка корректности работы стратегий сортировки
     * - Проверка функций генерации данных (из файла, вручную, случайно)
     */
    public static void run() {
        System.out.println("=== Запуск ручных тестов ===\n");

        CarBuilderTest.runTests();
        SortStrategyTest.runTests();
        DataGeneratorTest.runTests();

        System.out.println("=== Все тесты выполнены ===");
    }
}