package org.aston.app.util;

import java.util.Arrays;

/**
 * Утилитарный класс для валидации входных данных при создании объекта автомобиля (Car).
 * <p>
 * Содержит статические методы для проверки корректности значений полей:
 * модели, мощности и года выпуска. Используется при ручном вводе или чтении
 * данных из файла перед созданием экземпляра Car.
 */
public class InputValidator {

    /**
     * Проверяет, является ли переданная модель допустимой.
     * <p>
     * Модель считается валидной, если она присутствует в списке разрешённых моделей
     * (указанном в классе DataGenerator) без учёта регистра.
     *
     * @param model строка с названием модели автомобиля
     * @return true, если модель существует в списке допустимых; иначе false
     */
    public static boolean isValidModel(String model) {
        return Arrays.stream(DataGenerator.MODELS).anyMatch(model::equalsIgnoreCase);
    }

    /**
     * Проверяет, находится ли значение мощности в допустимом диапазоне.
     * <p>
     * Мощность (в лошадиных силах) должна быть положительной и не превышать
     * разумный технический предел.
     *
     * @param power целочисленное значение мощности
     * @return true, если мощность в диапазоне от 1 до 2000 включительно; иначе false
     */
    public static boolean isValidPower(int power) {
        return power >= 1 && power <= 2000;
    }

    /**
     * Проверяет, находится ли год выпуска в допустимом диапазоне.
     * <p>
     * Год должен быть не ранее первого выпуска автомобиля (1885) и не позже
     * установленного предельного года (в данном случае — 2025).
     *
     * @param year год выпуска автомобиля
     * @return true, если год находится в диапазоне от 1885 до 2025 включительно; иначе false
     */
    public static boolean isValidYear(int year) {
        return year >= 1885 && year <= 2025;
    }
}
