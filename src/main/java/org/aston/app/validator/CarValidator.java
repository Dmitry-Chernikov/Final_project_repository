package org.aston.app.validator;

import org.aston.app.exception.CarValidationException;
import org.aston.app.model.Car;

/**
 * Интерфейс CarValidator определяет контракт для валидации объектов класса Car.
 * <p>
 * Каждый класс, реализующий этот интерфейс, отвечает за проверку одного из полей автомобиля
 * (например, модель, мощность, год выпуска) на соответствие заданным правилам.
 * <p>
 * Реализации данного интерфейса используются в цепочке валидаторов для комплексной
 * проверки целостности объекта Car перед его использованием.
 */
public interface CarValidator {

    /**
     * Выполняет валидацию переданного объекта автомобиля.
     *
     * @param car объект Car, который необходимо проверить
     * @throws CarValidationException если значение поля не прошло проверку
     */
    void validate(Car car);
}
